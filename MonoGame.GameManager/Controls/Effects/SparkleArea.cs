namespace MonoGame.GameManager.Controls.Effects
{
    /// <summary>Where a <see cref="SparkleEffect"/> makes its sparkles appear.</summary>
    public enum SparkleArea
    {
        /// <summary>On the edge of the button (a little inside or outside).</summary>
        Border,

        /// <summary>Just outside the edge of the button.</summary>
        Around,

        /// <summary>Anywhere inside the button.</summary>
        Inside,

        /// <summary>Above the top edge of the button.</summary>
        Top
    }
}
