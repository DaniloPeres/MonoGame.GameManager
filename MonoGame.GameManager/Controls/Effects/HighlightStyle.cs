namespace MonoGame.GameManager.Controls.Effects
{
    /// <summary>The shape of a <see cref="HighlightEffect"/>.</summary>
    public enum HighlightStyle
    {
        /// <summary>A rounded band at the top of the button, like the reflection on candy or jelly buttons.</summary>
        Band,

        /// <summary>A thin line just under the top edge.</summary>
        Strip,

        /// <summary>A soft oval reflection at the top.</summary>
        Ellipse,

        /// <summary>A rounded band at the bottom of the button (light coming through it).</summary>
        Bottom
    }
}
